#!/usr/bin/env bash
# Install the machine-level parts of the redesigned Nightly (the panel's repo is cloned by restore.sh core;
# this wires it into the box). Idempotent: safe to re-run. Needs root for the system parts (uses sudo).
#
#   ./install-nightly.sh --planet  [options]   the box the panel and the agents live on
#   ./install-nightly.sh --station [options]   an offload box: only the nightly-node daemon
#
# Planet steps: nightly-node daemon (via the Nightly repo's install/install-node.sh), the x-nightly nginx site
#   (http://x-nightly -> the panel on :3010), scc on PATH plus the sccPath setting, a restart-panel shortcut.
# Station steps: the nightly-node daemon only (register it afterwards on the planet: nightly node add ...).
#
# Options
#   --repo DIR       Nightly checkout (default $NIGHTLY_REPO, else /home/core/projects/nightly)
#   --user USER      account that owns the checkout and runs the daemon and panel (default core)
#   --node-args "…"  extra arguments for install-node.sh (e.g. "--name box1 --kinds build,test --token T")
#   --scc-src FILE   scc binary to install into /usr/local/bin when scc is not on PATH
#                    (default: ~/bin/scc of the invoking user, else the release for $SCC_VERSION is downloaded)
#   --no-node  --no-nginx  --no-scc    skip a step
#   --dry-run        print what would be done
# Env: NIGHTLY_REPO, SCC_VERSION (default 4.1.0), NIGHTLY_NGINX_SITES (default /etc/nginx).
# No secrets live here: the node token is generated by install-node.sh (/etc/nightly-node/env) or passed with --node-args.
set -euo pipefail

mode="" repo="${NIGHTLY_REPO:-/home/core/projects/nightly}" user=core node_args="" scc_src="" dry=0
do_node=1 do_nginx=1 do_scc=1
scc_version="${SCC_VERSION:-4.1.0}"
nginx_root="${NIGHTLY_NGINX_SITES:-/etc/nginx}"

die() { echo "install-nightly: $*" >&2; exit 1; }
say() { echo "install-nightly: $*"; }
run() { if [ "$dry" = 1 ]; then echo "+ $*"; else "$@"; fi; }
asroot() { if [ "$(id -u)" = 0 ]; then run "$@"; else run sudo "$@"; fi; }
asuser() { if [ "$(id -un)" = "$user" ]; then run "$@"; else run sudo -u "$user" "$@"; fi; }

while [ $# -gt 0 ]; do
  case $1 in
    --planet) mode=planet ;;
    --station) mode=station ;;
    --repo) repo=${2:?--repo needs a value}; shift ;;
    --user) user=${2:?--user needs a value}; shift ;;
    --node-args) node_args=${2:?--node-args needs a value}; shift ;;
    --scc-src) scc_src=${2:?--scc-src needs a value}; shift ;;
    --no-node) do_node=0 ;;
    --no-nginx) do_nginx=0 ;;
    --no-scc) do_scc=0 ;;
    --dry-run) dry=1 ;;
    -h|--help) sed -n '2,21p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) die "unknown option $1 (try --help)" ;;
  esac
  shift
done
[ -n "$mode" ] || die "choose --planet or --station"
[ -d "$repo" ] || die "no Nightly checkout at $repo (run restore.sh core first, or pass --repo)"

# 1. nightly-node daemon: planet vs station is the installer's own switch.
if [ "$do_node" = 1 ]; then
  [ -x "$repo/install/install-node.sh" ] || die "$repo/install/install-node.sh missing; update the Nightly checkout"
  # shellcheck disable=SC2086  # node_args is deliberately word-split
  asroot "$repo/install/install-node.sh" "--$mode" --user "$user" $node_args
fi

[ "$mode" = planet ] || { say "station done"; exit 0; }

# 2. x-nightly nginx site (a copy, not a link: nginx's user cannot always read the checkout).
if [ "$do_nginx" = 1 ]; then
  src="$repo/deploy/nginx/x-nightly.conf"
  [ -f "$src" ] || die "missing $src"
  if ! command -v nginx >/dev/null 2>&1 && [ "$dry" = 0 ]; then
    say "nginx is not installed; skipping the x-nightly site (install nginx, then re-run)"
  else
    avail="$nginx_root/sites-available/x-nightly.conf" enabled="$nginx_root/sites-enabled/x-nightly.conf"
    asroot install -D -m644 "$src" "$avail"
    asroot mkdir -p "$nginx_root/sites-enabled"
    asroot ln -sfn "$avail" "$enabled"
    if [ "$dry" = 1 ]; then echo "+ nginx -t && systemctl reload nginx"
    elif asroot nginx -t; then asroot systemctl reload nginx
    else die "nginx -t failed; the site is installed but nginx was not reloaded"; fi
  fi
fi

# 3. scc on PATH (the LOC counter), then tell the panel where it is.
if [ "$do_scc" = 1 ]; then
  scc_bin=$(command -v scc 2>/dev/null || true)
  if [ -z "$scc_bin" ]; then
    if [ -z "$scc_src" ] && [ -x "${HOME:-/nonexistent}/bin/scc" ]; then scc_src=$HOME/bin/scc; fi
    if [ -n "$scc_src" ]; then
      [ -x "$scc_src" ] || die "--scc-src $scc_src is not an executable"
      asroot install -m755 "$scc_src" /usr/local/bin/scc
    else
      tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT
      url="https://github.com/boyter/scc/releases/download/v$scc_version/scc_Linux_x86_64.tar.gz"
      say "downloading $url"
      run curl -fsSL -o "$tmp/scc.tgz" "$url"
      run tar -xzf "$tmp/scc.tgz" -C "$tmp" scc
      asroot install -m755 "$tmp/scc" /usr/local/bin/scc
    fi
    scc_bin=/usr/local/bin/scc
  fi
  say "scc: $scc_bin"
  if [ "$dry" = 0 ] && [ -x "$scc_bin" ]; then "$scc_bin" --version; fi
  # The setting lives in the panel's database; if the CLI cannot reach it yet (fresh box), say how to set it later.
  if [ "$dry" = 1 ]; then echo "+ nightly set-setting sccPath $scc_bin"
  elif ! asuser "$repo/bin/nightly" set-setting sccPath "$scc_bin" >/dev/null 2>&1; then
    say "could not set sccPath (database not ready?); run later: nightly set-setting sccPath $scc_bin"
  fi
fi

# 4. restart-panel shortcut for the panel owner (scripts/restart-panel.sh; the panel is 'npm start' on :3010).
bindir=$(getent passwd "$user" | cut -d: -f6)/bin
asuser mkdir -p "$bindir"
asuser ln -sfn "$repo/scripts/restart-panel.sh" "$bindir/restart-panel"
say "planet done: http://x-nightly (panel :3010); restart it with $bindir/restart-panel"
